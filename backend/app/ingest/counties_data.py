def get_counties() -> list[dict]:
    """Return all counties as dicts with frost dates."""
    result = []
    for fips, name, state, lat, lon in COUNTIES:
        frost = _STATE_FROST_DEFAULTS.get(state, (270, 290, 310))
        result.append({
            "fips": fips,
            "name": name,
            "state": state,
            "latitude": lat,
            "longitude": lon,
            "frost_kill_10": frost[0],
            "frost_kill_50": frost[1],
            "frost_kill_90": frost[2],
        })
    return result


def get_soil_defaults() -> list[dict]:
    """Return default soil data for each county."""
    soils = []
    for fips, name, state, lat, lon in COUNTIES:
        awc = _STATE_AWC_DEFAULTS.get(state, 0.18)
        soil_type = _STATE_SOIL_DEFAULTS.get(state, "silt loam")
        soils.append({
            "county_fips": fips,
            "soil_type": soil_type,
            "awc": awc,
        })
    return soils


